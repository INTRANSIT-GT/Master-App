-- 3) Los avisos que destinaban a esos roles
update master.notificaciones set destinatarios = (
  select array_agg(case d when 'ENCARGADO' then 'OPERATIVO' when 'LIQUIDACIONES' then 'VALIDADOR'
    when 'COMERCIAL' then 'FACTURACION' when 'CONTABILIDAD' then 'COBROS'
    when 'GERENCIA_TRANSPORTE' then 'GERENTE_TRANSPORTE' when 'GERENCIA_COMERCIAL' then 'GERENTE_COMERCIAL'
    else d end) from unnest(destinatarios) as d)
  where destinatarios && array['ENCARGADO','LIQUIDACIONES','COMERCIAL','CONTABILIDAD','GERENCIA_TRANSPORTE','GERENCIA_COMERCIAL'];

