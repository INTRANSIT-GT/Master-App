-- 017 · Reorganización por departamentos: roles nuevos y migración de los existentes.
-- Los roles viejos (ENCARGADO, LIQUIDACIONES, COMERCIAL, CONTABILIDAD, GERENCIA_*) se mapean a los nuevos
